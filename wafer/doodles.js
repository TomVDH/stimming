// Flattens a doodle to segments [x0, y0, x1, y1], with y down.
export function segs(d) {
  const out = [];
  for (const line of d.lines) for (let i = 0; i + 1 < line.length; i++) out.push([line[i][0], -line[i][1], line[i + 1][0], -line[i + 1][1]]);
  return out;
}
