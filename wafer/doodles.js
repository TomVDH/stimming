// The ten chip doodles: flat single-metal line art, as chip designers drew them.
// Each doodle is a list of polylines in a box from -1 to 1 (y up); segs() flattens them.
const TAU = Math.PI * 2;
const arc = (cx, cy, rx, ry, a0, a1, n = 10) => Array.from({ length: n + 1 }, (_, i) => {
  const a = (a0 + (a1 - a0) * i / n) * TAU / 360;
  return [cx + rx * Math.cos(a), cy + ry * Math.sin(a)];
});
const ring = (cx, cy, r, n = 10) => arc(cx, cy, r, r, 0, 360, n);
const rectP = (x0, y0, x1, y1) => [[x0, y0], [x1, y0], [x1, y1], [x0, y1], [x0, y0]];
// A spiral from the centre outwards.
const spiral = (cx, cy, r0, r1, turns, n) => Array.from({ length: n + 1 }, (_, i) => {
  const t = i / n, a = t * turns * TAU, r = r0 + (r1 - r0) * t;
  return [cx + r * Math.cos(a), cy + r * Math.sin(a)];
});
const wave = (x0, y0, x1, amp, n) => Array.from({ length: n + 1 }, (_, i) => [x0 + (x1 - x0) * i / n, y0 + amp * Math.sin(i / n * 3 * TAU)]);

// Scales and centres a drawing so its larger side spans -1 to 1.
const norm = lines => {
  let x0 = 9, x1 = -9, y0 = 9, y1 = -9;
  for (const l of lines) for (const [x, y] of l) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
  const k = 2 / Math.max(x1 - x0, y1 - y0), cx = (x0 + x1) / 2, cy = (y0 + y1) / 2;
  return lines.map(l => l.map(([x, y]) => [(x - cx) * k, (y - cy) * k]));
};
// Pixel art: the outline of every filled cell edge that faces an empty cell.
const pixels = rows => {
  const h = rows.length, w = rows[0].length, on = (x, y) => x >= 0 && y >= 0 && x < w && y < h && rows[y][x] === '#';
  const out = [];
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    if (!on(x, y)) continue;
    const X = x - w / 2, Y = h / 2 - y;
    if (!on(x, y - 1)) out.push([[X, Y], [X + 1, Y]]);
    if (!on(x, y + 1)) out.push([[X, Y - 1], [X + 1, Y - 1]]);
    if (!on(x - 1, y)) out.push([[X, Y], [X, Y - 1]]);
    if (!on(x + 1, y)) out.push([[X + 1, Y], [X + 1, Y - 1]]);
  }
  return out;
};

